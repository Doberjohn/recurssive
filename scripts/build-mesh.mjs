#!/usr/bin/env node
/**
 * Mesh-gradient pipeline.
 *
 * The source files are 4000x2500 RGBA PNGs, ~25 MB each, used as full-bleed
 * background surfaces. They are pathological for any codec: their "noise" is
 * 1-pixel white noise (measured horizontal autocorrelation -0.050 to -0.063 at
 * lag 1), which is maximum-entropy and therefore uncompressible — but it is
 * also information-free and trivially regenerable.
 *
 * So: don't compress it, synthesise it.
 *   1. Downscale to 128x80 with lanczos3, which averages the noise away and
 *      leaves the smooth gradient. AVIF q80 -> 711-916 bytes each.
 *   2. Re-add grain at render time from one shared tile, via mix-blend-mode.
 *
 * Verified with sharp: 246.7 MB -> 7.6 KB, PSNR 40.5-42.3 dB against a
 * grain-free reference. Re-run scripts/probe-mesh.mjs to reproduce.
 *
 * Two properties worth knowing:
 *   - Banding from upscaling a 128px image is self-solving. ~90% of adjacent
 *     pixel steps land below 0.5 LSB and quantise flat; the grain overlay IS
 *     the dither that breaks them. The two requirements reinforce each other.
 *   - At this size the mesh falls below Chrome's 0.05 bits-per-pixel threshold
 *     for LCP candidacy, so it can never become the LCP element. The full-size
 *     original would have — and would have wrecked it.
 */
import sharp from 'sharp'
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const MESH_DIR =
  process.env.MESH_DIR ??
  'D:/johnn/Projects/recurssive/Recurssive Folder/Recurssive Folder/Mesh'
const OUT_CSS = 'src/app/generated/mesh.css'
// White noise is incompressible, so tile bytes scale linearly with area:
// 96px=3.9KB, 128px=6.7KB, 192px=14.8KB, 256px=26.6KB (WebP q80, measured).
// 128 is the knee — large enough that tiling periodicity is invisible at 10%
// opacity, small enough that the tile is not the dominant cost of this file.
const GRAIN_PX = 128
const MESH_W = 128
const MESH_H = 80

/** Deterministic PRNG so the grain tile is byte-identical on every build. */
function mulberry32(seed) {
  return function () {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Box-Muller gaussian noise, mid-grey centred. */
async function grainTile(size, sigma = 26) {
  const rand = mulberry32(0x5ec0_1a11)
  const buf = Buffer.allocUnsafe(size * size)
  for (let i = 0; i < buf.length; i++) {
    const u = Math.max(rand(), 1e-9)
    const v = rand()
    const g = Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v)
    buf[i] = Math.min(255, Math.max(0, Math.round(128 + g * sigma)))
  }
  return sharp(buf, { raw: { width: size, height: size, channels: 1 } })
    .webp({ quality: 80, effort: 6 })
    .toBuffer()
}

if (!existsSync(MESH_DIR)) {
  console.error(`✗ MESH_DIR not found: ${MESH_DIR}`)
  console.error('  Set MESH_DIR to the folder holding meshnoise-gradient-*.png')
  process.exit(1)
}

// Only the gradients the designs actually reference. 8 and 9 are unused.
const USED = [1, 2, 3, 4, 5, 6, 7, 10, 11, 12]
const available = readdirSync(MESH_DIR).filter((f) => f.endsWith('.png'))

mkdirSync('src/app/generated', { recursive: true })

const decls = []
let srcTotal = 0
let outTotal = 0

for (const n of USED) {
  const file = `meshnoise-gradient-${n}.png`
  if (!available.includes(file)) {
    console.warn(`  ! missing ${file} — skipped`)
    continue
  }
  const src = join(MESH_DIR, file)
  srcTotal += readFileSync(src).length

  const buf = await sharp(src)
    .resize(MESH_W, MESH_H, { kernel: 'lanczos3', fit: 'fill' })
    .avif({ quality: 80, effort: 9, chromaSubsampling: '4:4:4' })
    .toBuffer()
  outTotal += buf.length

  decls.push(`  --mesh-${n}: url("data:image/avif;base64,${buf.toString('base64')}");`)
  console.log(`  mesh-${String(n).padEnd(2)}  ${String(buf.length).padStart(4)} B`)
}

const grain = await grainTile(GRAIN_PX)
outTotal += grain.length
console.log(`  grain    ${grain.length} B  (${GRAIN_PX}x${GRAIN_PX} WebP, deterministic)`)

const css = `/* GENERATED by scripts/build-mesh.mjs — do not edit.
 * ${USED.length} mesh gradients + 1 grain tile.
 * ${(srcTotal / 1048576).toFixed(1)} MB of source PNG -> ${(outTotal / 1024).toFixed(1)} KB inline.
 * Inlined as data URIs: zero requests, and they cannot become the LCP element.
 */

:root {
${decls.join('\n')}
  --grain: url("data:image/webp;base64,${grain.toString('base64')}");
  /* Grain amplitude, calibrated per breakpoint. Independent noise averages down
   * with resampling, so the source amplitude is not what anyone ever saw:
   * measured sigma falls from ~13 at 4000px to ~6 at 1920px to ~2.5 at 768px. */
  --grain-opacity: 0.10;
}

@media (max-width: 768px) {
  :root { --grain-opacity: 0.05; }
}

/* Full-bleed mesh surface. Apply .mesh with a --mesh var:
 *   <div class="mesh" style={{ ['--mesh']: 'var(--mesh-6)' }} />
 */
.mesh {
  position: relative;
  background-image: var(--mesh, var(--mesh-1));
  background-size: cover;
  background-position: center;
  isolation: isolate;
}

/* Grain restores the texture the downscale removed, and doubles as the dither
 * that prevents banding in the upscaled gradient. */
.mesh::after {
  content: "";
  position: absolute;
  inset: 0;
  background-image: var(--grain);
  background-repeat: repeat;
  background-size: ${GRAIN_PX}px ${GRAIN_PX}px;
  mix-blend-mode: overlay;
  opacity: var(--grain-opacity);
  pointer-events: none;
  z-index: 1;
}

@media (prefers-reduced-transparency: reduce) {
  .mesh::after { display: none; }
}
`

writeFileSync(OUT_CSS, css)

console.log(
  `\n  ${(srcTotal / 1048576).toFixed(1)} MB  ->  ${(outTotal / 1024).toFixed(1)} KB` +
    `  (${Math.round(srcTotal / outTotal)}x)`
)
console.log(`  wrote ${OUT_CSS} (${(css.length / 1024).toFixed(1)} KB)\n`)
